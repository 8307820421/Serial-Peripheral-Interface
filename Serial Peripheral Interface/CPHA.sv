`timescale 1ns / 1ps
/*-------------------------------------------------------------------------------------------------------------------------------------*/
// start to decode the edges of clk.
/*-------------------------------------------------------------------------------------------------------------------------------------*/
module CPHA();
reg mosi = 0;
reg cpha = 1;
reg [7:0] tx_data = 8'b10101010;
reg [2:0] bit_count = 3'b111;
reg [2:0] state = 0;
reg cs = 0;
integer count = 0;
reg start = 0; 
reg clk = 0;
/*--------------------------------------------------------------------------------------------------------------------------------------*/
always #5 clk = ~clk;
initial begin
@(posedge clk);
start = 0;
@(posedge clk ) ;
start = 1;
end

/*--------------------------------------------------------------------------------------------------------------------------------------*/

always @ (posedge clk)
begin
case(state)
0: begin
       if (start)
       begin
           if (!cpha)  // 0
           begin
              state <= 1;
              cs    <= 0;
           end
           else begin  // delay occus if cpha 1 //
             state <= 3;
             cs    <= 0;
           end
      end
       else 
       state <= 0;
end

/*--------------------------------------------------------------------------------------------------------------------------------------*/
1: begin
   if (count <3)
   begin
     count <= count + 1;
     state <= 1;
     mosi <= tx_data[bit_count]; //MSB
   end
  else begin
    count <= 0;
    if (bit_count !=0)
    begin
      bit_count <= bit_count - 1; // until bit count 0 so that all bits accessed
      state <= 1;
    end
    else begin
      state <= 2;
    end
  end 
end

/*--------------------------------------------------------------------------------------------------------------------------------------*/
2: begin
  cs <=1'b1;
  bit_count <= 3'b111;
  state <= 0;
  mosi <= 1'b0;
end

/*--------------------------------------------------------------------------------------------------------------------------------------*/
3: begin   // if CPHA 1 then delay occurs hence used the states vacant ot introduce the delay
  state <= 4;
end

/*--------------------------------------------------------------------------------------------------------------------------------------*/
4: begin
  state <= 1;
end

/*--------------------------------------------------------------------------------------------------------------------------------------*/
 endcase
end
endmodule
